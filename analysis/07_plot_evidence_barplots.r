library(dplyr)
library(stringr)
library(ggplot2)

# 1. Helper function
format_k_m <- function(x) {
  case_when(
    x >= 1e6 ~ sprintf("%.1f M", x / 1e6),
    x >= 1e3 ~ sprintf("%.1f K", x / 1e3),
    TRUE ~ as.character(x)
  )
}

# 2. Load data
dat <- readRDS("data/plot_data/aggregated_plot_data.rds")

# 3. Abbreviation dictionary
abbreviations <- c(
  "GO_Catalytic"="GO", "Keyword_Catalytic"="KW", "Protein_Name"="Name",
  "Active_Site"="Site", "Reaction_Text"="Rxn", "Rhea_ID"="Rhea",
  "Enzyme_DB"="DB", "Text_Mining"="Text", "EC_Number"="EC", "\\|"=" + "
)

# 4. Data processing
df_plot <- dat$evidence %>%
  mutate(
    ev_count = if_else(evidence_field %in% c("None", ""), 0L, str_count(evidence_field, "\\|") + 1L),
    ev_group = case_when(
      ev_count == 0 ~ "0 Ev",
      ev_count == 1 ~ "1 Evidence",
      ev_count == 2 ~ "2 Evidences",
      TRUE ~ ">2 Evidences"
    ),
    evidence_clean = str_replace_all(evidence_field, abbreviations)
  ) %>%
  filter(ev_group != "0 Ev") %>%

  # Calculate the GRAND TOTAL for the entire EC Category
  group_by(has_ec) %>%
  mutate(total_ec_category = sum(count)) %>%

  # Calculate bucket totals and the bucket's percentage of the whole category
  group_by(has_ec, ev_group) %>%
  mutate(
    total_in_bucket = sum(count),
    bucket_pct_of_ec = (total_in_bucket / total_ec_category) * 100, # <--- NEW BUCKET %

    # Calculate the individual bar's share of the bucket to clean up tiny bars (<2%)
    bar_pct_of_bucket = (count / total_in_bucket) * 100,
    plot_category = if_else(bar_pct_of_bucket >= 2.0, evidence_clean, "Other (<2%)")
  ) %>%

  # Aggregate the cleaned data
  group_by(has_ec, ev_group, plot_category, total_in_bucket, total_ec_category, bucket_pct_of_ec) %>%
  summarize(count = sum(count), .groups = "drop") %>%

  mutate(
    # Recalculate the bar's final percentage within the bucket
    bar_pct_final = (count / total_in_bucket) * 100,

    # Format bar label to show "XX.X% (Y.Y M)"
    label_text = sprintf("%.1f%% (%s)", bar_pct_final, format_k_m(count)),

    has_ec = factor(has_ec, levels = c("With EC", "No EC")),
    ev_group = factor(ev_group, levels = c("1 Evidence", "2 Evidences", ">2 Evidences")),
    plot_category = str_remove_all(string = plot_category, pattern = "EC \\+ "),
    # Apply Confidence Tiers
    confidence_tier = case_when(
      plot_category == "EC" ~ "1. Enzyme activity",
      str_detect(plot_category, "Site|Rxn|Rhea|DB|EC") ~ "2. High (Biochemical/Structural)",
      str_detect(plot_category, "GO|KW") ~ "3. Medium (Ontology/Homology)",
      str_detect(plot_category, "Name|Text") ~ "4. Low (Lexical/Text)",
      TRUE ~ "5. Other/Mixed")
  )
# 5. Advanced Sorting & Facet Labels
df_plot <- df_plot %>%
  arrange(has_ec, ev_group) %>%
  mutate(
    # NEW: Create a dynamic facet title that includes both the Bucket N and its % of the Category
    panel_label = sprintf("%s | %s\n(N = %s | %.1f%% of %s)",
                          has_ec, ev_group, format_k_m(total_in_bucket), bucket_pct_of_ec, has_ec),
    panel_label = factor(panel_label, levels = unique(panel_label)),

    # Force "Other (<2%)" to always sit at the bottom of the Y-axis
    order_val = if_else(plot_category == "Other (<2%)", -Inf, as.numeric(count)),
    plot_category = reorder(plot_category, order_val)
  )

# 6. Semantic Palette
# 5. Semantic Palette
tier_palette <- c(
  "1. Enzyme activity"               = "#cc1616", # Red Enzyme
  "2. High (Biochemical/Structural)" = "#2b83ba", # Strong Blue
  "3. Medium (Ontology/Homology)"    = "#abdda4", # Soft Green
  "4. Low (Lexical/Text)"            = "#fdae61", # Warning Orange
  "5. Other/Mixed"                   = "#cccccc"  # Neutral Grey
)


# 7. Plotting
library(tidytext)
g_dodged_bars <- ggplot(df_plot, aes(
  x = count,
  # NEW: Order the categories by count, but STRICTLY within their specific facet
  y = reorder_within(plot_category, count, panel_label),
  fill = confidence_tier
)) +
  # Removed position_dodge, set width to 0.8 for nice proportional bars
  geom_col(color = "white", linewidth = 0.3, width = 0.3) +

  # Text labels placed just outside the bars
  geom_text(aes(label = label_text), hjust = -0.1, size = 3.5, fontface = "bold", color = "grey20") +

  facet_wrap(~ panel_label, ncol = 3, scales = "free") +

  # NEW: You MUST add this line to clean up the axis labels generated by reorder_within()
  scale_y_reordered() +

  # Expanded X axis by 35% so the longer text labels fit beautifully
  scale_x_continuous(expand = expansion(mult = c(0, 0.35))) +
  scale_fill_manual(values = tier_palette) +

  theme_minimal() +
  theme(
    strip.text = element_text(size = 12, face = "bold", margin = margin(b = 10, t = 10)),
    axis.text.y = element_text(size = 10, face = "bold"),
    axis.text.x = element_blank(),
    axis.title = element_blank(),
    panel.grid = element_blank(),
    legend.position = "bottom",
    legend.title = element_text(face = "bold")
  ) +
  labs(
    title = "Evidence Breakdown by Number of Annotations",
    subtitle = "Bars show % within their bucket. Facet titles show the bucket's % of all 'With EC' or 'No EC' entries.",
    fill = "Highest Evidence Class"
  )

print(g_dodged_bars)
ggsave("plots/07_evidence_dodged.png", g_dodged_bars, width=16, height=6, bg='white')
ggsave("plots/07_evidence_dodged.pdf", g_dodged_bars, width=16, height=6, bg='white')




