library(dplyr)
library(stringr)
library(ggplot2)
library(tidyr)     # Required for separate_rows()
library(tidytext)  # Required for reorder_within()

# 1. Helper function
format_k_m <- function(x) {
  case_when(
    x >= 1e6 ~ sprintf("%.1f M", x / 1e6),
    x >= 1e3 ~ sprintf("%.1f K", x / 1e3),
    TRUE ~ as.character(x)
  )
}

# 2. Load data
dat <- readRDS("data/plot_data/aggregated_plot_data.rds")

# 3. Abbreviation dictionary (We don't need the pipe replacement here since we split by pipe first)
abbreviations <- c(
  "GO_Catalytic"      = "GO",
  "Keyword_Catalytic" = "KW",
  "Protein_Name"      = "Name",
  "Active_Site"       = "Site",
  "Reaction_Text"     = "Rxn",
  "Rhea_ID"           = "Rhea",
  "Enzyme_DB"         = "DB",
  "Text_Mining"       = "Text",
  "EC_Number"         = "EC"
)

# 4. Data processing
# First, get the absolute total of entries in each EC category to calculate accurate percentages
ec_totals <- dat$evidence %>%
#  filter(primary_class == "Enzyme") %>%
  group_by(has_ec) %>%
  summarize(total_ec_category = sum(count), .groups = "drop")

df_marginal <- dat$evidence %>%
#  filter(primary_class != "Suspected_Enzyme") %>%
  filter(!evidence_field %in% c("None", "")) %>%
  # If a row had count=100 and evidence="GO|EC", it becomes two rows of 100 for "GO" and "EC".
  separate_rows(evidence_field, sep = "\\|") %>%
  # Apply abbreviations to the now-individual strings
  mutate(evidence_clean = str_replace_all(evidence_field, abbreviations)) %>%
  # Group by EC status and the single evidence type, then sum the overlaps
  group_by(has_ec, evidence_clean) %>%
  summarize(count = sum(count), .groups = "drop") %>%

  # Join the grand totals back in to calculate percentages
  left_join(ec_totals, by = "has_ec") %>%

  mutate(
    # Calculate percentage relative to the total number of proteins in the facet
    pct_of_category = (count / total_ec_category) * 100,
    label_text = sprintf("%.1f%% (%s)", pct_of_category, format_k_m(count)),

    has_ec = factor(has_ec, levels = c("With EC", "No EC")),

    # Apply Confidence Tiers
    confidence_tier = case_when(
      evidence_clean == "EC" ~ "1. Enzyme activity",
      str_detect(evidence_clean, "Site|Rxn|Rhea|DB") ~ "2. High (Biochemical/Structural)",
      str_detect(evidence_clean, "GO|KW") ~ "3. Medium (Ontology/Homology)",
      str_detect(evidence_clean, "Name|Text") ~ "4. Low (Lexical/Text)",
      TRUE ~ "5. Other/Mixed"
    )
  ) %>%
  arrange(has_ec, desc(count)) %>%
  mutate(
    # Dynamic facet label
    panel_label = sprintf("%s\n(Total Category N = %s)", has_ec, format_k_m(total_ec_category)),
    panel_label = factor(panel_label, levels = unique(panel_label))
  )

# 5. Semantic Palette
tier_palette <- c(
  "1. Enzyme activity"               = "#cc1616", # Red Enzyme
  "2. High (Biochemical/Structural)" = "#2b83ba", # Strong Blue
  "3. Medium (Ontology/Homology)"    = "#abdda4", # Soft Green
  "4. Low (Lexical/Text)"            = "#fdae61", # Warning Orange
  "5. Other/Mixed"                   = "#cccccc"  # Neutral Grey
)

# 6. Plotting
g_marginal_bars <- ggplot(df_marginal, aes(
  x = count,
  # Order the individual evidence types by count within their specific facet
  y = reorder_within(evidence_clean, count, panel_label),
  fill = confidence_tier
)) +
  # Set width to 0.5 for nicely spaced bars
  geom_col(color = "white", linewidth = 0.3, width = 0.5) +

  # Text labels placed just outside the bars
  geom_text(aes(label = label_text), hjust = -0.1, size = 4, fontface = "bold", color = "grey20") +

  # 2 Columns (With EC, No EC)
  facet_wrap(~ panel_label, ncol = 2, scales = "free") +

  # Clean up the axis labels generated by reorder_within()
  scale_y_reordered() +

  # Expanded X axis by 40% so the longer text labels fit perfectly
  scale_x_continuous(expand = expansion(mult = c(0, 0.4))) +
  scale_fill_manual(values = tier_palette) +

  theme_minimal() +
  theme(
    strip.text = element_text(size = 14, face = "bold", margin = margin(b = 10, t = 10)),
    axis.text.y = element_text(size = 12, face = "bold"),
    axis.text.x = element_blank(),
    axis.title = element_blank(),
    panel.grid = element_blank(),
    legend.position = "bottom",
    legend.title = element_text(face = "bold")
  ) +
  labs(
    title = "Presence of Individual Evidence Types",
    subtitle = "Bars show the % of entries containing each specific clue (Note: An entry can have multiple types of evidence).",
    fill = "Evidence Class"
  )

print(g_marginal_bars)
ggsave("plots/09_evidence_marginal.png", g_marginal_bars, width=12, height=6, bg='white')
ggsave("plots/09_evidence_marginal.pdf", g_marginal_bars, width=12, height=6, bg='white')

